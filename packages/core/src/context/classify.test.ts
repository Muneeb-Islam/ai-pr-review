import { describe, expect, it } from "vitest";
import { createPathClassifier, looksGenerated, SKIP_REASONS } from "./classify";
import { patch } from "./test-support";

const classifier = createPathClassifier({
  ignore: ["dist/**", "coverage/**", "**/*.lock"],
  secretPaths: ["**/.env*"],
});

describe("path exclusions (FR-08, FR-10)", () => {
  it.each([
    ["package-lock.json", SKIP_REASONS.lockfile],
    ["packages/a/yarn.lock", SKIP_REASONS.lockfile],
    ["pnpm-lock.yaml", SKIP_REASONS.lockfile],
    ["Cargo.lock", SKIP_REASONS.lockfile],
    ["assets/logo.png", SKIP_REASONS.binary],
    ["fonts/a.woff2", SKIP_REASONS.binary],
    ["node_modules/left-pad/index.js", SKIP_REASONS.vendored],
    ["packages/x/node_modules/y/index.js", SKIP_REASONS.vendored],
    ["vendor/lib/a.js", SKIP_REASONS.vendored],
    ["dist/index.js", SKIP_REASONS.buildOutput],
    ["packages/core/dist/index.js", SKIP_REASONS.buildOutput],
    ["coverage/lcov.info", SKIP_REASONS.buildOutput],
    [".next/server/page.js", SKIP_REASONS.buildOutput],
    ["public/app.min.js", SKIP_REASONS.generated],
    ["src/__snapshots__/a.test.ts.snap", SKIP_REASONS.generated],
    ["src/api.generated.ts", SKIP_REASONS.generated],
  ])("excludes %s", (path, reason) => {
    expect(classifier.excludedBy(path)).toBe(reason);
  });

  it.each([
    [".env"],
    [".env.local"],
    ["apps/api/.env.production"],
    ["certs/server.pem"],
    ["deploy/private.key"],
    ["home/.ssh/id_rsa"],
    [".npmrc"],
    ["config/credentials.json"],
    ["infra/prod.tfvars"],
    ["infra/terraform.tfstate"],
  ])("treats %s as a secret file", (path) => {
    expect(classifier.excludedBy(path)).toBe(SKIP_REASONS.secret);
    expect(classifier.isSecretPath(path)).toBe(true);
  });

  it("applies the ignore and secret_paths settings on top of the built-ins", () => {
    const custom = createPathClassifier({
      ignore: ["docs/legacy/", "*.fixture.ts"],
      secretPaths: ["config/prod/**"],
    });
    expect(custom.excludedBy("docs/legacy/old.md")).toBe(SKIP_REASONS.ignored);
    expect(custom.excludedBy("src/deep/a.fixture.ts")).toBe(SKIP_REASONS.ignored);
    expect(custom.excludedBy("config/prod/settings.ts")).toBe(SKIP_REASONS.secret);
    expect(custom.excludedBy(".env")).toBe(SKIP_REASONS.secret);
  });

  it("keeps built-in secret patterns even when secret_paths is emptied", () => {
    const none = createPathClassifier({ ignore: [], secretPaths: [] });
    expect(none.excludedBy(".env")).toBe(SKIP_REASONS.secret);
    expect(none.excludedBy("id_ed25519")).toBe(SKIP_REASONS.secret);
  });

  it("does not exclude ordinary source, tests or docs", () => {
    for (const path of [
      "src/index.ts",
      "src/credentials.ts",
      "src/build.ts",
      "test/a.test.ts",
      "README.md",
      ".github/workflows/ci.yml",
      "src/environment.ts",
    ]) {
      expect(classifier.excludedBy(path)).toBeUndefined();
    }
  });

  it("reports the secret reason first when several rules match", () => {
    const both = createPathClassifier({ ignore: [".env*"], secretPaths: [] });
    expect(both.excludedBy(".env")).toBe(SKIP_REASONS.secret);
  });
});

describe("priority", () => {
  it("orders source, tests, config, docs", () => {
    const order = ["src/a.ts", "src/a.test.ts", "tsconfig.json", "README.md"].map((p) =>
      classifier.priority(p),
    );
    expect(order).toEqual([...order].sort((a, b) => a - b));
    expect(new Set(order).size).toBe(4);
  });

  it("recognises test directories", () => {
    expect(classifier.isTestPath("packages/a/__tests__/x.ts")).toBe(true);
    expect(classifier.isTestPath("test/x.ts")).toBe(true);
    expect(classifier.isTestPath("src/x.spec.ts")).toBe(true);
    expect(classifier.isTestPath("src/x.ts")).toBe(false);
  });
});

describe("looksGenerated", () => {
  it("detects a generated banner at the top of a new file", () => {
    const banner = patch(
      "@@ -0,0 +1,3 @@",
      "+// Code generated by protoc. DO NOT EDIT.",
      "+export {};",
      "+",
    );
    expect(looksGenerated("src/a.ts", banner)).toBe(true);
    expect(
      looksGenerated("src/a.ts", patch("@@ -0,0 +1,2 @@", "+/* @generated */", "+export {};")),
    ).toBe(true);
  });

  it("ignores the marker in a hunk that does not start at line 1", () => {
    const middle = patch("@@ -40,1 +40,2 @@", " a", "+// DO NOT EDIT this constant");
    expect(looksGenerated("src/a.ts", middle)).toBe(false);
  });

  it("detects minified scripts by very long lines", () => {
    const long = `+${"a=1;".repeat(700)}`;
    expect(looksGenerated("public/app.js", patch("@@ -1 +1 @@", "-x", long))).toBe(true);
    expect(looksGenerated("data/blob.json", patch("@@ -1 +1 @@", "-x", long))).toBe(false);
  });
});
